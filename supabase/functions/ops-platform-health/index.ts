function ageMinutes(value: string | null | undefined) {
  if (!value) return null;
  const timestamp = new Date(value).getTime();
  if (Number.isNaN(timestamp)) return null;
  return Math.max(0, Math.round((Date.now() - timestamp) / 60000));
}

function cadenceLabel(minutes: number | null | undefined) {
  if (!minutes) return "On demand";
  return minutes === 1 ? "Every minute" : `Every ${minutes} minutes`;
}

function nextRunFromCadence(lastRunAt: string | null | undefined, cadenceMinutes: number | null | undefined, active: boolean) {
  if (!active || !cadenceMinutes) return null;
  const cadenceMs = cadenceMinutes * 60000;
  const nowMs = Date.now();
  const lastRunMs = lastRunAt ? new Date(lastRunAt).getTime() : NaN;
  const baseMs = Number.isNaN(lastRunMs) ? nowMs : lastRunMs;
  let nextMs = baseMs + cadenceMs;
  if (nextMs <= nowMs) {
    nextMs = baseMs + (Math.floor((nowMs - baseMs) / cadenceMs) + 1) * cadenceMs;
  }
  return new Date(nextMs).toISOString();
}

function etaMinutes(value: string | null | undefined) {
  if (!value) return null;
  const timestamp = new Date(value).getTime();
  if (Number.isNaN(timestamp)) return null;
  return Math.max(0, Math.ceil((timestamp - Date.now()) / 60000));
}

function freshnessStatus(age: number | null, warnMinutes: number, failMinutes: number) {
  if (age == null) return "unknown";
  if (age >= failMinutes) return "critical";
  if (age >= warnMinutes) return "warning";
  return "healthy";
}

function ageSeconds(value: string | null | undefined) {
  if (!value) return null;
  const timestamp = new Date(value).getTime();
  if (Number.isNaN(timestamp)) return null;
  return Math.max(0, Math.round((Date.now() - timestamp) / 1000));
}

