async function fetchLatestAndCount(
  sb: any,
  table: string,
  locationId: string,
  columns: string,
  orderColumn: string,
) {
  const [{ data: latestRow, error: latestError }, { count, error: countError }] = await Promise.all([
    sb.from(table).select(columns).eq("location_id", locationId).order(orderColumn, { ascending: false }).limit(1).maybeSingle(),
    sb.from(table).select("id", { count: "exact", head: true }).eq("location_id", locationId),
  ]);

  if (latestError) throw latestError;
  if (countError) throw countError;

  return {
    latest: latestRow || null,
    count: count ?? 0,
  };
}

async function fetchPresenceSyncHealth(sb: any, locationId: string) {
  const [{ data: latestRun, error: latestError }, { data: latestEvent, error: eventError }, { data: configRow, error: configError }] = await Promise.all([
    sb
      .from("facility_presence_sync_runs")
      .select("id, status, started_at, completed_at, duration_ms, current_count, arrivals_count, departures_count, duplicate_animals_count, errors")
      .eq("location_id", locationId)
      .order("started_at", { ascending: false })
      .limit(1)
      .maybeSingle(),
    sb
      .from("facility_presence_events")
      .select("event_key, event_type, computed_at, animal_name, animal_gingr_id")
      .eq("location_id", locationId)
      .order("computed_at", { ascending: false })
      .limit(1)
      .maybeSingle(),
    sb
      .from("lite_settings")
      .select("setting_value")
      .eq("location_id", locationId)
      .eq("setting_key", "presence_sync_config_v1")
      .maybeSingle(),
  ]);

  if (latestError) throw latestError;
  if (eventError) throw eventError;
  if (configError) throw configError;

  const intervalSeconds = presenceHealthInterval(configRow?.setting_value);
  const completedAge = ageSeconds(latestRun?.completed_at || null);
  const warnSeconds = (intervalSeconds * 3) + 5;
  const failSeconds = (intervalSeconds * 6) + 10;
  let status = freshnessStatus(completedAge == null ? null : completedAge / 60, warnSeconds / 60, failSeconds / 60);
  let message = latestRun?.completed_at
    ? `Last presence sync completed ${completedAge}s ago.`
    : "No completed presence sync run found.";

  if (latestRun?.status === "failed") {
    status = "critical";
    message = presenceRunErrorMessage(latestRun) || "Latest presence sync run failed.";
  } else if (latestRun?.status === "running" && ageSeconds(latestRun.started_at) != null && ageSeconds(latestRun.started_at)! > 120) {
    status = "critical";
    message = "Presence sync has been running for more than 2 minutes.";
  }

  return {
    status,
    message,
    interval_seconds: intervalSeconds,
    warn_seconds: warnSeconds,
    fail_seconds: failSeconds,
    latest_run: latestRun || null,
    latest_event: latestEvent || null,
    latest_completed_age_seconds: completedAge,
    config: configRow?.setting_value || null,
  };
}

async function fetchCountReconciliationHealth(sb: any, locationId: string, date: string) {
  const [matrixRes, rollCallRes] = await Promise.all([
    sb
      .from("scheduling_matrix_daily")
      .select("detail_json, computed_at")
      .eq("location_id", locationId)
      .eq("matrix_date", date)
      .maybeSingle(),
    sb
      .from("lite_daily_ops")
      .select("id, computed_items, computed_at, updated_at")
      .eq("location_id", locationId)
      .in("id", [
        `ops_roll_call_opening_${date}`,
        `ops_roll_call_closing_${date}`,
      ]),
  ]);

  if (matrixRes.error) throw matrixRes.error;
  if (rollCallRes.error) throw rollCallRes.error;

  const matrixDisplay = matrixRes.data?.detail_json?.display || {};
  const rollCallById = new Map((rollCallRes.data || []).map((row: any) => [row.id, row]));
  const openingRow: any = rollCallById.get(`ops_roll_call_opening_${date}`) || null;
  const closingRow: any = rollCallById.get(`ops_roll_call_closing_${date}`) || null;
  const openingMatrix = numericValue(matrixDisplay.opening?.total_boarding);
  const closingMatrix = numericValue(matrixDisplay.closing?.total_boarding);
  const openingRollCall = numericValue(openingRow?.computed_items?.summary?.totalDogs);
  const closingRollCall = numericValue(closingRow?.computed_items?.summary?.totalDogs);

  const checks = [
    {
      key: "opening_boarding",
      label: "Opening boarding",
      matrix_total: openingMatrix,
      roll_call_total: openingRollCall,
      status: openingMatrix == null || openingRollCall == null
        ? "warning"
        : openingMatrix === openingRollCall
          ? "healthy"
          : "critical",
    },
    {
      key: "closing_boarding",
      label: "Closing boarding",
      matrix_total: closingMatrix,
      roll_call_total: closingRollCall,
      status: closingMatrix == null || closingRollCall == null
        ? "warning"
        : closingMatrix === closingRollCall
          ? "healthy"
          : "critical",
    },
  ];

  const missingLabels = checks
    .filter((check) => check.matrix_total == null || check.roll_call_total == null)
    .map((check) => check.label);
  const mismatches = checks
    .filter((check) => check.status === "critical")
    .map((check) => `${check.label}: matrix ${check.matrix_total}, roll call ${check.roll_call_total}`);
  const status = worstStatus(checks.map((check) => check.status));
  const summary = mismatches.length
    ? mismatches.join("; ")
    : missingLabels.length
      ? `Missing count source for ${missingLabels.join(", ")}`
      : "Scheduling matrix and roll-call dog totals agree.";

  return {
    status,
    summary,
    date,
    matrix_computed_at: matrixRes.data?.computed_at || null,
    opening_roll_call_computed_at: openingRow?.computed_at || openingRow?.updated_at || null,
    closing_roll_call_computed_at: closingRow?.computed_at || closingRow?.updated_at || null,
    checks,
  };
}

